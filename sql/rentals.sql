-- Apply before starting the wallet-backed lease/order projections.
-- Actor journals remain the source of truth; monetary amounts are CNY yuan with two decimal places.
CREATE TABLE IF NOT EXISTS lease_view (
  lease_id VARCHAR(255) NOT NULL,
  user_id VARCHAR(255),
  phase VARCHAR(64) NOT NULL DEFAULT 'NEW',
  period_seq BIGINT NOT NULL DEFAULT 0,
  current_order_id VARCHAR(255),
  current_plan_unit VARCHAR(16),
  current_plan_quantity INT,
  current_amount DECIMAL(19,2),
  current_starts_at TIMESTAMP(6) NULL,
  current_ends_at TIMESTAMP(6) NULL,
  last_period_ends_at TIMESTAMP(6) NULL,
  renewal_plan_unit VARCHAR(16),
  renewal_plan_quantity INT,
  plan_revision BIGINT NOT NULL DEFAULT 0,
  auto_renew BOOLEAN NOT NULL DEFAULT FALSE,
  pending_order_id VARCHAR(255),
  pending_period_seq BIGINT,
  pending_plan_unit VARCHAR(16),
  pending_plan_quantity INT,
  pending_amount DECIMAL(19,2),
  pending_plan_revision BIGINT,
  pending_phase VARCHAR(64),
  settlement_order_id VARCHAR(255),
  settlement_amount DECIMAL(19,2),
  settlement_deduct_amount DECIMAL(19,2),
  terminated_at TIMESTAMP(6) NULL,
  next_action_at TIMESTAMP(6) NULL,
  error TEXT,
  workflow_version BIGINT NOT NULL,
  updated_at TIMESTAMP(6) NOT NULL,
  PRIMARY KEY (lease_id),
  INDEX idx_lease_due (next_action_at, lease_id),
  INDEX idx_lease_user (user_id, updated_at, lease_id)
) ENGINE=InnoDB;

CREATE TABLE IF NOT EXISTS order_view (
  order_id VARCHAR(255) NOT NULL,
  user_id VARCHAR(255),
  lease_id VARCHAR(255),
  amount DECIMAL(19,2) NOT NULL DEFAULT 0.00,
  phase VARCHAR(64) NOT NULL DEFAULT 'NEW',
  deduct_amount DECIMAL(19,2),
  error TEXT,
  workflow_version BIGINT NOT NULL,
  updated_at TIMESTAMP(6) NOT NULL,
  PRIMARY KEY (order_id),
  INDEX idx_order_lease (lease_id, updated_at, order_id)
) ENGINE=InnoDB;
